import urllib.request,json,csv,io,gzip
from pathlib import Path
base='https://raw.githubusercontent.com/modood/Administrative-divisions-of-China/master/'
p=Path('cloudfunctions/medicalApi/region-data');p.mkdir(exist_ok=True)
tree=json.load(urllib.request.urlopen(base+'dist/pcas-code.json',timeout=60));idx={};towns={}
for province in tree:
 for city in province['children']:
  for county in city['children']:
   for town in county['children']:
    town['children']=[];towns[town['code']]=town
with urllib.request.urlopen(base+'dist/villages.csv',timeout=120) as r:
 for row in csv.DictReader(io.TextIOWrapper(r,encoding='utf-8-sig')):
  parent=towns.get(row['streetCode'])
  if parent is not None:parent['children'].append({'code':row['code'],'name':row['name']})
for province in tree:
 raw=json.dumps(province,ensure_ascii=False,separators=(',',':')).encode();(p/(province['code']+'.json.gz')).write_bytes(gzip.compress(raw,mtime=0))
index=[{'code':p['code'],'name':p['name'],'children':[{'code':c['code'],'name':c['name'],'children':[{'code':a['code'],'name':a['name']} for a in c['children']]} for c in p['children']]} for p in tree]
(p/'index.json').write_text(json.dumps(index,ensure_ascii=False,separators=(',',':')),encoding='utf-8')
(p/'SOURCE.md').write_text('Source: https://github.com/modood/Administrative-divisions-of-China\nDataset: 2023-06-30; upstream no longer updated. License: WTFPL.\nAll 31 mainland provinces, prefectures, counties, townships and villages. Generated by scripts/build-regions.py; no patient data.\n',encoding='utf-8')
print({'provinces':len(tree),'townships':len(towns),'villages':sum(len(t['children']) for t in towns.values()),'compressed_bytes':sum(x.stat().st_size for x in p.glob('*'))})
